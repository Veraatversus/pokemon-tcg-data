const AQUAPOLIS_1537_ORDER = AQUAPOLIS_1537_CARDS.map(({ productId }) => productId);
const AQUAPOLIS_1537_COLLECTOR_BY_ID = new Map(
  AQUAPOLIS_1537_CARDS.map(({ productId, collectorNumber }) => [productId, collectorNumber])
);

function indexCardsByProductId(cards) {
  return new Map(cards.map((card, index) => [Number(card?.cardmarketProductId || 0), { card, index }]));
}

export function transformSet(payload, { logger = console } = {}) {
  if (!payload || !Array.isArray(payload.cards)) {
    return payload;
  }

  const cardsById = indexCardsByProductId(payload.cards);
  const orderedCards = [];
  const seenIds = new Set();

  for (const productId of AQUAPOLIS_1537_ORDER) {
    const entry = cardsById.get(productId);

    if (!entry) {
      logger.warn(`[cardmarket-custom-sets/1537] missing product ${productId}`);
      continue;
    }

    seenIds.add(productId);
    orderedCards.push({
      ...entry.card,
      collectorNumber: AQUAPOLIS_1537_COLLECTOR_BY_ID.get(productId) ?? null,
    });
  }

  const remainingCards = payload.cards
    .filter((card) => !seenIds.has(Number(card?.cardmarketProductId || 0)))
    .map((card) => {
      const productId = Number(card?.cardmarketProductId || 0);
      return {
        ...card,
        collectorNumber: AQUAPOLIS_1537_COLLECTOR_BY_ID.get(productId) ?? card.collectorNumber ?? null,
      };
    });

  if (remainingCards.length > 0) {
    logger.warn(`[cardmarket-custom-sets/1537] appended ${remainingCards.length} unexpected cards after Aquapolis order`);
  }

  return {
    ...payload,
    cards: [...orderedCards, ...remainingCards],
  };
}