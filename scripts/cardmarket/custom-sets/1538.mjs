/**
 * Transforms the set payload by reordering cards and assigning collector numbers
 * based on the Cardmarket search results for Skyridge (1538).
 */
export function transformSet(payload, { logger = console } = {}) {
  if (!payload || !Array.isArray(payload.cards)) {
    return payload;
  }

  const cardMap = new Map();
  for (const card of SKYRIDGE_1538) {
    cardMap.set(String(card.productId), card.collectorNumber);
  }

  const reordered = [];
  const missing = [];

  for (const [productId, collectorNumber] of cardMap) {
    const found = payload.cards.find(
      (c) => String(c?.cardmarketProductId) === productId
    );
    if (found) {
      reordered.push({ ...found, collectorNumber });
    } else {
      missing.push(productId);
    }
  }

  if (missing.length > 0) {
    logger.warn(`[cardmarket-custom-sets/1538] ${missing.length} card(s) not found in payload: ${missing.join(", ")}`);
  }

  return {
    ...payload,
    cards: reordered,
  };
}
