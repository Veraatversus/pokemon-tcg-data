const EXPEDITION_1536_ORDER = EXPEDITION_1536_CARDS.map(({ productId }) => productId);
const EXPEDITION_1536_COLLECTOR_BY_ID = new Map(
  EXPEDITION_1536_CARDS.map(({ productId, collectorNumber }) => [productId, collectorNumber])
);

function indexCardsByProductId(cards) {
  return new Map(cards.map((card, index) => [Number(card?.cardmarketProductId || 0), { card, index }]));
}

export function transformSet(payload, { logger = console } = {}) {
  if (!payload || !Array.isArray(payload.cards)) {
    return payload;
  }

  const cardsById = indexCardsByProductId(payload.cards);
  const orderedCards = [];
  const seenIds = new Set();

  for (const productId of EXPEDITION_1536_ORDER) {
    const entry = cardsById.get(productId);

    if (!entry) {
      logger.warn(`[cardmarket-custom-sets/1536] missing product ${productId}`);
      continue;
    }

    seenIds.add(productId);
    orderedCards.push({
      ...entry.card,
      collectorNumber: EXPEDITION_1536_COLLECTOR_BY_ID.get(productId) ?? null,
    });
  }

  const remainingCards = payload.cards
    .filter((card) => !seenIds.has(Number(card?.cardmarketProductId || 0)))
    .map((card) => {
      const productId = Number(card?.cardmarketProductId || 0);
      return {
        ...card,
        collectorNumber: EXPEDITION_1536_COLLECTOR_BY_ID.get(productId) ?? card.collectorNumber ?? null,
      };
    });

  if (remainingCards.length > 0) {
    logger.warn(`[cardmarket-custom-sets/1536] appended ${remainingCards.length} unexpected cards after Expedition Base Set order`);
  }

  return {
    ...payload,
    cards: [...orderedCards, ...remainingCards],
  };
}
