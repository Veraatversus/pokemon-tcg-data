test('dom enthaelt exakt die erwarteten Schluessel (statisch aus dem Quelltext)', () => {
  const src = fs.readFileSync(new URL('../js/app/dom.js', import.meta.url), 'utf8').split(/\r?\n/);
  const start = src.findIndex((l) => l === 'export const dom = {');
  assert.ok(start >= 0, 'export const dom nicht gefunden');
  const end = src.findIndex((l, i) => i > start && l === '};');
  assert.ok(end > start, 'Ende von dom nicht gefunden');
  const keys = src.slice(start + 1, end).map((l) => l.match(/^  (\w+):/)?.[1]).filter(Boolean);
  assert.deepEqual(keys, EXPECTED_KEYS);
});
